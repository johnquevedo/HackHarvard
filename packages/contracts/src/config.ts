import { z } from "zod";
export const AppConfigSchema = z.object({
  nodeEnv: z.enum(["development", "test", "production"]).default("development"),
  dennisMode: z.enum(["live", "hybrid", "sim"]).default("hybrid"),
  conversationMode: z.enum(["normal", "demo"]).default("normal"),
  // Temporary: "video" makes Dennis answer only the exact recorded script (packages/platform/src/scripted-demo.ts).
  // "hybrid" plays every script in packages/platform/src/demo-scripts.ts word for word alongside live Dennis.
  demoScript: z.enum(["off", "video", "hybrid"]).default("off"),
  // Milliseconds of iMessage typing bubble before every message Dennis sends (0 = send at once).
  typingMs: z.coerce.number().int().min(0).max(10000).default(0),
  // Background planning: how long a chat must be quiet before Dennis compiles a plan (0 = off).
  planningQuietMs: z.coerce.number().int().min(0).default(120000),
  portServer: z.coerce.number().int().min(1).max(65535).default(4000),
  portWeb: z.coerce.number().int().min(1).max(65535).default(3000),
  databaseUrl: z.string().default("file:./data/dennis.db"),
  dennisAdminToken: z.string().min(16),
  dennisTz: z.string().default("America/New_York"),
  dennisRegionCode: z.string().default("boston-cambridge"),
  dennisAckMode: z.enum(["none", "reaction"]).default("none"),
  approvalTtlMinutes: z.coerce.number().positive().default(30),
  logLevel: z.string().default("info"),
  nextPublicApiMode: z.enum(["live", "mock"]).default("live"),
  apiBaseUrl: z.string().url().default("http://localhost:4000"),
  demoAliceHandle: z.string().default("alice@example.test"),
  demoBobHandle: z.string().default("bob@example.test"),
  demoJohnHandle: z.string().default("john@example.test"),
  demoStevenHandle: z.string().default("steven@example.test"),
  demoIsaacHandle: z.string().default("isaac@example.test"),
  demoFriendHandle: z.string().default("friend@example.test"),
  // First name for the person on DEMO_FRIEND_HANDLE (Dennis addresses people by first name).
  demoFriendName: z.string().min(1).default("Friend"),
  demoScenario: z.enum(["legacy", "group"]).default("legacy"),
  photonMode: z.enum(["live", "sim"]).default("sim"),
  photonApiBaseUrl: z.string().url().default("https://api.photon.codes"),
  photonInbound: z.enum(["socketio", "webhook"]).default("socketio"),
  photonSpaceMode: z.enum(["direct", "group", "either"]).default("direct"),
  photonAccountKey: z.string().default("primary"),
  nessieMode: z.enum(["live", "sim"]).default("sim"),
  nessieBaseUrl: z.string().default("http://api.nessieisreal.com"),
  nessieMaxTransferCents: z.coerce.number().int().positive().default(50000),
  llmProvider: z.enum(["anthropic", "chalk", "mock"]).default("mock"),
  llmModel: z.string().default("claude-sonnet-5-5"),
  llmTimeoutMs: z.coerce.number().int().positive().default(8000),
  liveTests: z.enum(["0", "1"]).default("0"),
  photonProjectId: z.string().optional(),
  photonProjectSecret: z.string().optional(),
  photonApiKey: z.string().optional(),
  photonAgentUserId: z.string().optional(),
  photonSocketUrl: z.string().optional(),
  photonWebhookSecret: z.string().optional(),
  nessieApiKey: z.string().optional(),
  nessieRunTag: z.string().optional(),
  anthropicApiKey: z.string().optional(),
  chalkApiToken: z.string().optional(),
  chalkGatewayBaseUrl: z.string().optional(),
  chalkGatewayModel: z.string().optional(),
});
export type AppConfig = z.infer<typeof AppConfigSchema>;
